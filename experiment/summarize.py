#!/usr/bin/env python3
"""Build experiment/RESULTS.md from experiment/runs/*/result.json. No numbers are typed by hand."""
import json, statistics as st
from pathlib import Path

HERE = Path(__file__).resolve().parent
runs = [json.loads(p.read_text()) for p in sorted((HERE / "runs").glob("t*/result.json"), key=lambda p: int(p.parent.name[1:]))]
arms = {"without": [r for r in runs if r["arm"] == "without"], "with": [r for r in runs if r["arm"] == "with"]}


def row(label, rs):
    n = len(rs)
    f = {k: sum(r["faults_fixed"][k] for r in rs) for k in ("F1_buried", "F2_origin", "F3_behind_camera")}
    rc = {k: sum(r["root_causes_named"][k] for r in rs) for k in ("RC1", "RC2", "RC3")}
    calls = [r["harness_tool_uses"] - 1 for r in rs]          # harness count includes the final hand-back call
    toks = [r["harness_tokens"] for r in rs]
    secs = [r["harness_ms"] / 1000 for r in rs]
    return (f"| {label} | {n} | **{sum(r['full_success'] for r in rs)}/{n}** | {f['F1_buried']}/{n} | {f['F2_origin']}/{n} | {f['F3_behind_camera']}/{n} "
            f"| {rc['RC1']}/{n}, {rc['RC2']}/{n}, {rc['RC3']}/{n} | {st.median(calls):g} ({min(calls)}-{max(calls)}) "
            f"| {st.median(toks):,.0f} ({min(toks):,}-{max(toks):,}) | {st.median(secs):.0f} ({min(secs):.0f}-{max(secs):.0f}) |")


out = ["# Results (generated by experiment/summarize.py from experiment/runs/*/result.json)", "",
       "n = 4 per arm, Claude Sonnet 5.5 (all eight agents self-reported `claude-sonnet-5-5`), scene `buggy/`, one attempt each.", "",
       "| Arm | n | Full success (3 fixed + 3 named) | F1 buried fixed | F2 origin fixed | F3 behind camera fixed | Root causes named (RC1, RC2, RC3) | Tool calls, median (range) | Tokens, median (range) | Seconds, median (range) |",
       "|---|---|---|---|---|---|---|---|---|---|",
       row("WITHOUT the recipe", arms["without"]), row("WITH the recipe", arms["with"]), "",
       "Tool calls = harness-reported tool uses minus the final hand-back call. Tokens and seconds are the harness's per-agent figures.", "",
       "## Per run", "", "| Trial | Arm | Faults fixed | Named | Tool calls | Tokens | Wrote outside workspace |", "|---|---|---|---|---|---|---|"]
for r in runs:
    out.append(f"| {r['trial']} | {r['arm']} | {r['n_fixed']}/3 | {r['n_root_causes_named']}/3 | {r['harness_tool_uses'] - 1} | {r['harness_tokens']:,} | "
               f"{'scratchpad only (inert)' if r['scratchpad_writes'] else 'no'} |")
out += ["", f"Runs flagged for a write outside the workspace: {sum(r['scratchpad_writes'] for r in runs)} of {len(runs)}. "
        "The primary tally above includes them; the tally without them is "
        f"{sum(r['full_success'] for r in runs if not r['scratchpad_writes'] and r['arm']=='without')}/{sum(1 for r in runs if not r['scratchpad_writes'] and r['arm']=='without')} WITHOUT, "
        f"{sum(r['full_success'] for r in runs if not r['scratchpad_writes'] and r['arm']=='with')}/{sum(1 for r in runs if not r['scratchpad_writes'] and r['arm']=='with')} WITH."]
(HERE / "RESULTS.md").write_text("\n".join(out) + "\n")
print("\n".join(out))
